-- 0002: roles (STUDENT / ADMIN) and student ID verification with admin review.
-- Additive only: new columns have defaults, new tables are new, nothing is dropped,
-- and existing rows keep working with code deployed before this migration.

-- ---------------------------------------------------------------- roles + verification status

-- Students sign up through /register and are always STUDENT. ADMIN accounts are only
-- created by the server-side scripts/bootstrap-admin.mjs; no endpoint changes a role.
ALTER TABLE users
  ADD COLUMN role text NOT NULL DEFAULT 'STUDENT'
    CONSTRAINT users_role_check CHECK (role IN ('STUDENT', 'ADMIN')),
  -- Denormalised copy of the latest verification decision, so permission checks are one row read.
  ADD COLUMN verification_status text NOT NULL DEFAULT 'UNVERIFIED'
    CONSTRAINT users_verification_status_check CHECK (verification_status IN (
      'UNVERIFIED', 'PENDING', 'APPROVED', 'REJECTED', 'RESUBMISSION_REQUIRED'));

-- Admin accounts are not students, so they have no NIM. Students still must have one.
ALTER TABLE users ALTER COLUMN nim DROP NOT NULL;
ALTER TABLE users ADD CONSTRAINT users_student_nim_check CHECK (role = 'ADMIN' OR nim IS NOT NULL);

-- Anyone a verifier already marked as verified keeps that status.
UPDATE users SET verification_status = 'APPROVED' WHERE student_verified_at IS NOT NULL;

CREATE INDEX users_admin_idx ON users (id) WHERE role = 'ADMIN';

-- ---------------------------------------------------------------- submissions

-- One row per attempt. A rejected or "resubmit" attempt stays as history; the student's
-- next attempt is a new row. Every decision is an explicit admin action: OCR only fills
-- the ocr_* columns and never changes `status`.
CREATE TABLE verification_submissions (
  id                   integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id              integer NOT NULL REFERENCES users (id) ON DELETE CASCADE,
  status               text NOT NULL DEFAULT 'PENDING' CHECK (status IN (
                         'PENDING', 'APPROVED', 'REJECTED', 'RESUBMISSION_REQUIRED')),

  -- What the student typed, as shown on their card.
  full_name            text NOT NULL CHECK (char_length(full_name) BETWEEN 2 AND 120),
  student_number       text NOT NULL CHECK (char_length(student_number) BETWEEN 4 AND 30),
  university           text NOT NULL CHECK (char_length(university) BETWEEN 2 AND 120),

  -- Private image in `files` (kind 'idcard'), served only to admins via an authorised route.
  -- Set to NULL when the retention policy deletes the image.
  id_image_key         text REFERENCES files (key) ON DELETE SET NULL,
  id_image_deleted_at  timestamptz,

  -- OCR assistance (see src/server/verification/).
  ocr_status           text NOT NULL DEFAULT 'not_configured' CHECK (ocr_status IN (
                         'not_configured', 'pending', 'completed', 'failed')),
  ocr_provider         text,
  ocr_raw_text         text,              -- cleared together with the image
  ocr_confidence       real,
  ocr_extracted        jsonb,             -- { fullName, studentNumber, university }
  ocr_comparison       jsonb,             -- per-field result: match | partial | mismatch | not_found
  ocr_has_mismatch     boolean,
  ocr_error            text,
  ocr_completed_at     timestamptz,

  -- The admin decision.
  reviewer_id          integer REFERENCES users (id),
  reviewed_at          timestamptz,
  decision_reason      text,              -- shown to the student (required to reject / ask to resubmit)
  admin_notes          text,              -- internal, never shown to the student

  submitted_at         timestamptz NOT NULL DEFAULT now(),
  updated_at           timestamptz NOT NULL DEFAULT now(),

  CONSTRAINT verification_reason_required CHECK (
    status NOT IN ('REJECTED', 'RESUBMISSION_REQUIRED')
    OR char_length(btrim(coalesce(decision_reason, ''))) >= 5),
  CONSTRAINT verification_review_recorded CHECK (
    (status = 'PENDING' AND reviewer_id IS NULL AND reviewed_at IS NULL)
    OR (status <> 'PENDING' AND reviewer_id IS NOT NULL AND reviewed_at IS NOT NULL)),
  CONSTRAINT verification_not_self_review CHECK (reviewer_id IS NULL OR reviewer_id <> user_id)
);
CREATE INDEX verification_submissions_user_idx ON verification_submissions (user_id, submitted_at DESC);
CREATE INDEX verification_submissions_status_idx ON verification_submissions (status, submitted_at);
-- At most one submission under review per student (also checked in the service, under a row lock).
CREATE UNIQUE INDEX verification_one_pending_per_user ON verification_submissions (user_id)
  WHERE status = 'PENDING';
-- One verified account per student ID number.
CREATE UNIQUE INDEX verification_approved_number_key ON verification_submissions (student_number)
  WHERE status = 'APPROVED';
-- Retention sweeps look for reviewed submissions that still hold an image.
CREATE INDEX verification_retention_idx ON verification_submissions (reviewed_at)
  WHERE id_image_key IS NOT NULL AND status <> 'PENDING';

-- Audit trail: who did what to each submission, and when.
CREATE TABLE verification_events (
  id             integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  submission_id  integer NOT NULL REFERENCES verification_submissions (id) ON DELETE CASCADE,
  actor_id       integer REFERENCES users (id),   -- NULL for system actions (OCR, retention)
  action         text NOT NULL CHECK (action IN (
                   'submitted', 'approved', 'rejected', 'resubmission_requested',
                   'ocr_completed', 'ocr_failed', 'image_deleted')),
  note           text,
  created_at     timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX verification_events_submission_idx ON verification_events (submission_id, id);
